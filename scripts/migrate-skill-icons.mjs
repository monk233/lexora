#!/usr/bin/env node
/* Migrate the legacy static SVG gallery into a typed frontend module.
 *
 * Source of truth: `web/shared/skill-icons.js`, which assigns
 * `LP.CUSTOM_SKILL_ICON_SVGS = { "<key>": '<svg …>' }`. The file is evaluated
 * in a bare VM sandbox (it only touches `window`), so the migration is
 * mechanical instead of hand-copied, and the key set is cross-checked against
 * `frontend/src/lib/constants.ts` (`CUSTOM_SKILL_ICON_KEYS`, 202 keys).
 *
 * Why a committed table rather than a dynamic `lucide-react` lookup: importing
 * the package namespace pulls every icon into the bundle and blows the 2 MB
 * budget; the legacy SVG payload is ~68 KB uncompressed.
 *
 * Usage: node scripts/migrate-skill-icons.mjs
 */
import { readFile, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import vm from "node:vm";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const SOURCE = join(ROOT, "web/shared/skill-icons.js");
const CONSTANTS = join(ROOT, "frontend/src/lib/constants.ts");
const TARGET = join(ROOT, "frontend/src/lib/settings/skill-icons.ts");
const EXPECTED_KEYS = 202;

function fail(message) {
  throw new Error(`migrate-skill-icons: ${message}`);
}

/** Evaluate the legacy browser-global file against a minimal `window`. */
function loadLegacySvgs(source) {
  const sandbox = { window: {} };
  vm.runInNewContext(source, sandbox, { filename: "web/shared/skill-icons.js" });
  const lp = sandbox.window.LP;
  if (!lp || typeof lp.CUSTOM_SKILL_ICON_SVGS !== "object" || lp.CUSTOM_SKILL_ICON_SVGS === null) {
    fail("LP.CUSTOM_SKILL_ICON_SVGS was not defined by web/shared/skill-icons.js");
  }
  return lp.CUSTOM_SKILL_ICON_SVGS;
}

/** Read the generated-key contract from the hand-maintained constants module. */
function loadConstantKeys(source) {
  const block = /export const CUSTOM_SKILL_ICON_KEYS: string\[\] = \[([\s\S]*?)\];/.exec(source);
  if (!block) fail("could not locate CUSTOM_SKILL_ICON_KEYS in frontend/src/lib/constants.ts");
  return [...block[1].matchAll(/"([^"]+)"/g)].map((match) => match[1]);
}

function assertKeySet(svgs, constants) {
  const keys = Object.keys(svgs).sort();
  if (keys.length !== EXPECTED_KEYS) {
    fail(`expected ${EXPECTED_KEYS} icons, found ${keys.length}`);
  }
  if (constants.length !== EXPECTED_KEYS) {
    fail(`constants.ts declares ${constants.length} icon keys, expected ${EXPECTED_KEYS}`);
  }
  const missing = constants.filter((key) => !Object.prototype.hasOwnProperty.call(svgs, key));
  const extra = keys.filter((key) => !constants.includes(key));
  if (missing.length || extra.length) {
    fail(
      `key set mismatch (missing: ${missing.join(", ") || "none"}; extra: ${
        extra.join(", ") || "none"
      })`
    );
  }
}

function renderModule(svgs) {
  const keys = Object.keys(svgs).sort();
  const lines = keys.map((key) => `  ${JSON.stringify(key)}: ${JSON.stringify(svgs[key])},`);
  return [
    "/* Generated by scripts/migrate-skill-icons.mjs from web/shared/skill-icons.js.",
    " * Do not edit by hand: rerun `node scripts/migrate-skill-icons.mjs`.",
    " *",
    " * Static copy of the curated Lucide gallery (202 icons) so the picker never",
    " * imports the whole icon package into the settings bundle.",
    " *",
    " * Lucide — https://lucide.dev — ISC license.",
    " * Copyright (c) for portions of Lucide are held by Cole Bemis 2013-2022 as",
    " * part of Feather (MIT); all other copyright (c) Lucide Contributors 2022.",
    " * License: https://github.com/lucide-icons/lucide/blob/main/LICENSE",
    " */",
    "",
    "export const CUSTOM_SKILL_ICON_SVGS: Record<string, string> = {",
    ...lines,
    "};",
    "",
  ].join("\n");
}

function assertSafeSvg(svgs) {
  for (const [key, svg] of Object.entries(svgs)) {
    if (typeof svg !== "string" || !svg.trimStart().startsWith("<svg")) {
      fail(`icon ${key} is not an inline <svg> string`);
    }
    if (/<script|onload=|javascript:/i.test(svg)) {
      fail(`icon ${key} contains active content`);
    }
  }
}

const legacySource = await readFile(SOURCE, "utf8");
const constantsSource = await readFile(CONSTANTS, "utf8");
const svgs = loadLegacySvgs(legacySource);
const constants = loadConstantKeys(constantsSource);

assertKeySet(svgs, constants);
assertSafeSvg(svgs);

const moduleSource = renderModule(svgs);
await writeFile(TARGET, moduleSource, "utf8");

const sizeKb = (Buffer.byteLength(moduleSource, "utf8") / 1024).toFixed(1);
console.log(
  `wrote frontend/src/lib/settings/skill-icons.ts (${Object.keys(svgs).length} icons, ${sizeKb} KB)`
);
